-- =================================================================
-- STEP 7. Create the student_scores view from a LEFT OUTER JOIN,
--         then query it twice
-- =================================================================

-- Create a view showing students and their test scores.
-- LEFT OUTER JOIN includes students who have no scores.
CREATE VIEW student_scores AS
SELECT
    students.student_id,
    CONCAT(students.first_name, ' ', students.last_name)
        AS student_name,
    test_scores.test_name,
    test_scores.score
FROM students
LEFT OUTER JOIN test_scores
    ON students.student_id = test_scores.student_id;

-- Display all students and their test scores.
SELECT * FROM student_scores;

-- Display only Maria Elena Jimenez's test scores.
SELECT * FROM student_scores
WHERE student_id = 3;


-- =================================================================
-- STEP 8. Create the calculate_gpa function
--
-- Paste the block from the handout in here so it is part of what you
-- submit, then RUN IT AT THE COMMAND PROMPT, not in VS Code.
--
-- DELIMITER is an instruction to the mysql command prompt program. It is
-- not SQL. Run it here and the server rejects it with
--   ERROR 1064 ... near 'DELIMITER $$' at line 1
-- =================================================================
DELIMITER $$

CREATE FUNCTION calculate_gpa(p_student_id INT)
RETURNS DECIMAL(4,2)
DETERMINISTIC
READS SQL DATA
BEGIN
    DECLARE v_gpa DECIMAL(4,2);

    SELECT ROUND(AVG(score), 2)
    INTO v_gpa
    FROM test_scores
    WHERE student_id = p_student_id
      AND score IS NOT NULL;

    RETURN IFNULL(v_gpa, 0.00);
END$$

DELIMITER ;

-- =================================================================
-- STEP 9. Run the function and fill in every gpa
-- =================================================================

-- Calculate and update the GPA for every student.
UPDATE students
SET gpa = calculate_gpa(student_id);

-- Display all students with their updated GPA.
