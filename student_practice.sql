-- Change the delimiter for creating triggers.
DELIMITER $$

-- Automatically recalculate GPA after adding a test score.
CREATE TRIGGER trg_scores_after_insert
AFTER INSERT ON test_scores
FOR EACH ROW
BEGIN
    UPDATE students
    SET gpa = calculate_gpa(NEW.student_id)
    WHERE student_id = NEW.student_id;
END$$

-- Automatically recalculate GPA after changing a test score.
CREATE TRIGGER trg_scores_after_update
AFTER UPDATE ON test_scores
FOR EACH ROW
BEGIN
    UPDATE students
    SET gpa = calculate_gpa(NEW.student_id)
    WHERE student_id = NEW.student_id;
END$$

-- Restore the normal delimiter.
DELIMITER ;
-- Check that both GPA triggers were created.
SHOW TRIGGERS;

-- Recalculate Jenna's GPA after her existing quiz4 score.
UPDATE students
SET gpa = calculate_gpa(student_id)
WHERE student_id = 1;

-- Show Jenna's GPA before testing the update trigger.
